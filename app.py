import math

# Area of a circle
radius = 5
circle_area = math.pi * radius ** 2
print(f"Circle area (r={radius}): {circle_area}")

# Area of a rectangle
length = 10
width = 4
rectangle_area = length * width
print(f"Rectangle area (l={length}, w={width}): {rectangle_area}")

# Area of a square
side = 6
square_area = side ** 2
print(f"Square area (s={side}): {square_area}")
